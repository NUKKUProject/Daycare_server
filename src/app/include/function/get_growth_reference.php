function getReferenceData($indicator, $sex) {
    $data = [];

    switch ($indicator) {
        case 'weight':
            $data = $sex === 'M' ? getWeightDataBoys() : getWeightDataGirls();
            break;
        case 'height':
            $data = $sex === 'M' ? getHeightDataBoys() : getHeightDataGirls();
            break;
        case 'bmi':
            $data = $sex === 'M' ? getBMIDataBoys() : getBMIDataGirls();
            break;
    }

    return $data;
}

function getAges() {
